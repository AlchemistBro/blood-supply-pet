// Package ui — набор шаблонов и компонентов интерфейса web (ADR-0007, docs/ui/style-guide.md).
//
// Состав: макет страницы (шапка с ролью, клиникой, логином и водяным знаком запаса NFR015, навигация по роли,
// хлебные крошки, подвал с пометкой «демо»), компоненты (таблица с сортировкой на сервере и пагинацией, бейдж
// статуса O07, ошибки полей и сводка ошибок, подтверждение на <dialog> с формой-фолбэком, уведомления после
// POST/redirect, пустые состояния, карточка «ключ — значение») и функции шаблонов.
//
// Правила, которые держит пакет:
//   - экранирование только стандартное html/template; доверенные типы (HTML, JS, URL) из данных не строятся;
//   - в шаблонах нет встроенных скриптов, атрибутов style и обработчиков on* — CSP без 'unsafe-inline' (ADR-0018);
//   - всё работает без JavaScript, htmx лишь ускоряет (hx-* атрибуты);
//   - в шапке только логин, роль и клиника: у модели пользователя нет полей для ФИО (CONTRIBUTING.md, правила канона).
//
// Экраны (пакеты страниц сервиса) передают свои шаблоны через Options.Pages: каждый файл определяет "content" и,
// при необходимости, "page_actions". Данные экрана — в Page.Content.
